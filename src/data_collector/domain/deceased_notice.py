"""備考の自由文から「その個体が死亡した」記載を見つける (T424)

自治体の収容一覧は、死亡が確認された個体をすぐ削除せず、備考欄に
「令和8年9月13日 死亡確認」と書き足したまま掲載期間の終わりまで残すことがある
(2026-09-18 越谷市（保護猫）で実測)。oneco 側は備考を読んでいなかったため、
死亡した子を「収容中」として公開し続けていた。

判定は次の二方向の実害の間に置く:
- 拾えない → 死亡した子を収容中として公開し続ける (問い合わせ先に無駄足)
- 誤検知 → 生きている子が公開から消える (迷子の飼い主が探せなくなる)

そのため「この個体が死んだ」と読める表記だけを拾い、次は意図的に外す:
- 飼い主・家族の死 (「飼い主が死亡したため引き取り」= 動物は生きていて譲渡対象)
- 制度・方針の文言 (「殺処分ゼロ」「安楽死は行っていません」)
- 手続きの案内 (「犬が死亡した場合は届出が必要です」)
"""

from __future__ import annotations

import re

# 「この個体が死んだ」と読める表記。
_DEATH_RE = re.compile(
    r"死亡確認"
    r"|死亡を確認"
    r"|死亡(?:し(?:た|ました|ています)|済)"
    r"|死体"
    r"|へい死"
    r"|斃死"
    r"|死没"
    r"|亡くなり(?:ました)?"
    r"|亡くなっ(?:た|ています)"
)

# 死んだのが動物ではない場合。一致語の手前 12 文字以内に出たら死亡記載と見なさない。
_OTHER_SUBJECT_RE = re.compile(r"飼い?主|飼主|所有者|家族|同居人|世帯主")

# 死亡そのものでなく、手続きの案内や仮定の話である場合。一致語の後ろ 12 文字以内を見る。
# 「ペットが死亡したとき」「犬が死亡した場合は届出が必要です」のような案内文は、
# 自治体ページのナビゲーションに必ず載っている (2026-09-18 に全 213 サイトを実測した
# ところ、死亡の語を含む 33 ページのうち 32 ページがこの種の定型文だった)。
_PROCEDURE_RE = re.compile(
    r"届出|届け出|届け|申請|手続|登録の抹消|連絡してください|連絡ください"
    r"|とき|場合|際に|際は|処理|引き取|引取"
)

# 「動物死体の引き取り」のような、個体ではなく死体処理サービスを指す語。
# 一致語が死体系のとき、その直前 4 文字に出たら個体の死亡記載と見なさない。
_CARCASS_WORDS = ("死体", "へい死", "斃死")
_GENERIC_CARCASS_RE = re.compile(r"動物|犬猫|ペット")


def deceased_notice(text: str | None) -> str | None:
    """個体の死亡を示す語が見つかればその語を、無ければ None を返す。

    戻り値を語にしているのは、公開から外した理由をログに残せるようにするため。

    Args:
        text: 備考・特徴などの自由文

    Returns:
        一致した語 (例 "死亡確認")。該当しなければ None
    """
    if not text:
        return None

    for m in _DEATH_RE.finditer(text):
        before = text[max(0, m.start() - 12) : m.start()]
        after = text[m.end() : m.end() + 12]
        if _OTHER_SUBJECT_RE.search(before):
            continue
        if _PROCEDURE_RE.search(after):
            continue
        if m.group(0) in _CARCASS_WORDS and _GENERIC_CARCASS_RE.search(
            text[max(0, m.start() - 4) : m.start()]
        ):
            continue
        return m.group(0)
    return None
