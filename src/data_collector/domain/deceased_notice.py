"""備考の自由文から「その個体が死亡した」記載を見つける (T424)

自治体の収容一覧は、死亡が確認された個体をすぐ削除せず、備考欄に
「令和8年9月13日 死亡確認」と書き足したまま掲載期間の終わりまで残すことがある
(2026-09-18 越谷市（保護猫）で実測)。oneco 側は備考を読んでいなかったため、
死亡した子を「収容中」として公開し続けていた。

**この判定は全サイトには掛けない。** 使うのは、死亡を備考に書くと実測できた
adapter だけ (現在は `city_koshigaya`)。理由は誤検知の実害が大きく、かつ譲渡
ページの紹介文がその温床になるため:

    母猫が死亡したため人工哺育で育ちました
    きょうだいは死亡しましたが、この子は順調に育っています
    路上で死体となっていた母猫のそばで保護されました

いずれも生きている子の紹介文で、死んだのは別の個体や飼い主である。2026-09-18 の
公開データでは description を持つ 205 件のうち 171 件が譲渡カテゴリの職員による
手書き紹介文で、この文体が毎日流れてくる。全サイトに掛けると、拾えるのは越谷の
1 件だけなのに、この面のリスクを全部背負うことになる。

判定を掛ける側は、短く構造化された備考欄 (越谷の「長尾 短毛 首輪なし 令和8年
9月13日 死亡確認」のような欄) であることを確かめてから使うこと。

拾えないと死亡した子を収容中として公開し続け、誤検知すると生きている子が公開から
消える。どちらも実害だが、後者は迷子の飼い主がその子を見つけられなくなるため、
迷ったら拾わない側に倒す。
"""

from __future__ import annotations

import re

# 「この個体が死んだ」と読める表記。体言止め (「令和8年9月13日 死亡」) も拾う。
_DEATH_RE = re.compile(
    r"死亡確認"
    r"|死亡を確認"
    r"|死亡が確認"
    r"|死亡"
    r"|死体"
    r"|へい死"
    r"|斃死"
    r"|死没"
    r"|衰弱死"
    r"|永眠"
    r"|他界"
    r"|亡くなり(?:ました)?"
    r"|亡くなっ(?:た|ています)"
)

# 死んだのが対象の個体ではない場合に出てくる語。一致語と同じ文 (「。」「改行」区切り) に
# 前後どちらでも出たら、死亡記載と見なさない。「路上で死体となっていた母猫のそばで
# 保護されました」のように主語が後ろに来る書き方があるため後ろも見る。
_OTHER_SUBJECT_RE = re.compile(
    r"飼い?主|飼主|所有者|世帯主|家族|同居人"
    r"|おばあ|おじい|祖母|祖父|高齢者施設"
    r"|母猫|母犬|父猫|父犬|親が|親の|きょうだい|兄弟|姉妹|同胎|他の[０-９0-9]*[頭匹]"
)

# 死亡そのものでなく、手続きの案内や仮定の話である場合。一致語の後ろ 12 文字以内を見る。
# 「ペットが死亡したとき」「犬の登録・変更・死亡届」のような案内文は自治体ページの
# ナビゲーションに必ず載っている (2026-09-18 に全 213 サイトを実測したところ、死亡の語を
# 含む 33 ページのうち 32 ページがこの種の定型文だった)。
_PROCEDURE_RE = re.compile(
    r"届|申請|手続|登録の抹消|連絡してください|連絡ください|とき|場合|際に|際は|処理|引き取|引取"
)

# 「動物死体の引き取り」のような、個体ではなく死体処理サービスを指す語。
# 一致語が死体系のとき、その直前 4 文字に出たら個体の死亡記載と見なさない。
_CARCASS_WORDS = ("死体", "へい死", "斃死")
_GENERIC_CARCASS_RE = re.compile(r"動物|犬猫|ペット")

_SENTENCE_SEP = re.compile(r"[。\n]")


def deceased_notice(text: str | None) -> str | None:
    """個体の死亡を示す語が見つかればその語を、無ければ None を返す。

    戻り値を語にしているのは、公開から外した理由をログに残せるようにするため。

    Args:
        text: 備考などの短い自由文。譲渡ページの紹介文には使わないこと
            (モジュールの説明を参照)

    Returns:
        一致した語 (例 "死亡確認")。該当しなければ None
    """
    if not text:
        return None

    for m in _DEATH_RE.finditer(text):
        if _OTHER_SUBJECT_RE.search(_sentence_around(text, m.start())):
            # 死んだのが飼い主・母猫・きょうだい等。対象の個体は生きている
            continue
        if _PROCEDURE_RE.search(text[m.end() : m.end() + 12]):
            continue
        if m.group(0) in _CARCASS_WORDS and _GENERIC_CARCASS_RE.search(
            text[max(0, m.start() - 4) : m.start()]
        ):
            continue
        return m.group(0)
    return None


def _sentence_around(text: str, index: int) -> str:
    """index を含む文 (「。」か改行で区切った範囲) を返す"""
    start = 0
    end = len(text)
    for m in _SENTENCE_SEP.finditer(text):
        if m.end() <= index:
            start = m.end()
        else:
            end = m.start()
            break
    return text[start:end]
